/**
 * Railway infrastructure for the x402 platform: STAGING (Base Sepolia, test money only).
 *
 *   railway config plan     # preview against the linked environment
 *   railway config apply    # apply after review
 *
 * Topology mirrors production: the public x402.org facilitator is primary (production: Coinbase CDP)
 * and our self-hosted facilitator is the fallback, reachable only on the private network.
 *
 * Secrets are never in this file. They appear as preserve() and are set out of band
 * (docs/staging.md): ADMIN_TOKEN and SESSION_SECRET on the gateway, FACILITATOR_PRIVATE_KEY and AUTH_TOKEN on the
 * facilitator. Services that need a secret reference the owner's variable instead of copying it.
 * Do NOT use ctx.randomString for secrets: it is a deterministic hash of the environment and label.
 *
 * Variables are managed: a variable missing from this file is deleted on apply.
 */
import { defineRailway, github, postgres, preserve, project, service } from "railway/iac";

const REPO = "stevegee1/x_402_call";
/** Staging payee, generated by `pnpm staging:wallets` (key in the operator's Keychain: x402-staging-pay-to). */
const STAGING_PAY_TO = "0x35E13c683A70fBe048CDB897cE1bAe36440fcd19";
/** Base Sepolia block when the staging payee was created: reconciliation scans from here. */
const STAGING_RECONCILE_FROM_BLOCK = "54079340";
const BASE_SEPOLIA_RPC = "https://sepolia.base.org";

const GATEWAY_PORT = "8080";
const FACILITATOR_PORT = "8090";
const RECONCILER_PORT = "8095";
const INGEST_ENV_PORT = "8091";

/** One image for every service (Dockerfile); each service redeploys only when its inputs change. */
const build = (app: string) => ({
  builder: "DOCKERFILE" as const,
  dockerfilePath: "Dockerfile",
  watchPatterns: [`/${app}/**`, "/packages/**", "/db/**", "/Dockerfile", "/package.json", "/pnpm-lock.yaml", "/pnpm-workspace.yaml"],
});

/**
 * The git branch staging builds from. It tracks this branch so the setup can be proven on staging
 * before merging; switch it to "main" (and re-apply) when the PR merges.
 */
const STAGING_BRANCH = "feat/staging-railway";
const source = github(REPO, { branch: STAGING_BRANCH, checkSuites: true });

const deploy = (startCommand: string, healthcheckPath: string) => ({
  startCommand,
  healthcheckPath,
  healthcheckTimeout: 120,
  restartPolicyType: "ON_FAILURE" as const,
  restartPolicyMaxRetries: 10,
  // Let in-flight requests and settlements finish before the old container stops.
  drainingSeconds: 30,
});

export default defineRailway((ctx) => {
  if (!ctx.isEnvironment("staging")) {
    throw new Error(`.railway/railway.ts describes staging only; refusing to plan or apply "${ctx.environment}"`);
  }

  const db = postgres("postgres");

  const facilitator = service("facilitator", {
    source,
    build: build("apps/facilitator"),
    // /healthz, not /readyz: an unfunded gas wallet must not block deploys. Readiness (chain id and
    // gas) is reported on /readyz and in metrics.
    deploy: deploy("pnpm --filter @mx/facilitator start", "/healthz"),
    // Exactly one replica: transaction nonces are assigned in-process (MVP.md R12).
    replicas: { sfo: 1 },
    // Private only: the gateway is its sole client. No public domain.
    networking: { privateNetworkEndpoint: "facilitator" },
    env: {
      NODE_ENV: "production",
      PORT: FACILITATOR_PORT,
      LOG_LEVEL: "info",
      NETWORK: "eip155:84532",
      RPC_URL: BASE_SEPOLIA_RPC,
      ALLOWED_PAY_TO: STAGING_PAY_TO,
      FACILITATOR_PRIVATE_KEY: preserve(),
      AUTH_TOKEN: preserve(),
    },
  });

  const gateway = service("@mx/gateway", {
    source,
    build: build("apps/gateway"),
    deploy: deploy("pnpm --filter @mx/gateway start", "/readyz"),
    replicas: { sfo: 1 },
    networking: { privateNetworkEndpoint: "mxgateway" },
    env: {
      NODE_ENV: "production",
      PORT: GATEWAY_PORT,
      LOG_LEVEL: "info",
      PUBLIC_BASE_URL: "https://${{RAILWAY_PUBLIC_DOMAIN}}",
      DATABASE_URL: db.env.DATABASE_URL,
      ADMIN_TOKEN: preserve(),

      X402_NETWORK: "eip155:84532",
      PAY_TO: STAGING_PAY_TO,
      FACILITATOR: "x402org",
      FACILITATOR_TIMEOUT_MS: "10000",
      FALLBACK_FACILITATOR_URL: `http://facilitator.railway.internal:${FACILITATOR_PORT}`,
      FALLBACK_FACILITATOR_AUTH_TOKEN: facilitator.env.AUTH_TOKEN,
      SETTLEMENT_MODE: "async",
      EXPOSURE_CAP_USD: "25",
      EXPOSURE_CAP_PER_PAYER_USD: "1",
      BASE_RPC_URL: BASE_SEPOLIA_RPC,
      FX_PROVIDER: "coinbase",

      // Products. Maritime runs on simulated AIS (labelled "simulated"; never sold on mainnet).
      DATA_SOURCE: "simulator",
      GRID_ENABLED: "true",
      // Grid is served from the version store that ingest-env writes (memory, point-in-time history),
      // instead of polling NESO from the gateway.
      GRID_SOURCE: "store",

      // x402 sessions: pay once, read at memory speed; SSE push is paid from a session.
      SESSIONS_ENABLED: "true",
      SESSION_SECRET: preserve(),

      // ERC-8004 buyer tiers on the canonical Base Sepolia registries. No trusted reviewers yet,
      // so buyers can reach "identified" but not "trusted".
      ERC8004_ENABLED: "true",
    },
  });

  const reconciler = service("reconciler", {
    source,
    build: build("packages/reconcile"),
    deploy: deploy("pnpm --filter @mx/reconcile start", "/healthz"),
    replicas: { sfo: 1 },
    networking: { privateNetworkEndpoint: "reconciler" },
    env: {
      PORT: RECONCILER_PORT,
      RECONCILE_GATEWAY_URL: `http://mxgateway.railway.internal:${GATEWAY_PORT}`,
      ADMIN_TOKEN: gateway.env.ADMIN_TOKEN,
      RPC_URL: BASE_SEPOLIA_RPC,
      NETWORK: "eip155:84532",
      PAY_TO: STAGING_PAY_TO,
      RECONCILE_FROM_BLOCK: STAGING_RECONCILE_FROM_BLOCK,
      RECONCILE_INTERVAL_MS: "900000",
    },
  });

  // Every published NESO version, for point-in-time history (architecture.md §6). History only
  // exists from the moment this runs, so it runs on staging ahead of the hot path. It exits until
  // the gateway has run migration 004; ON_FAILURE restarts cover that on a first deploy.
  const ingestEnv = service("ingest-env", {
    source,
    build: build("apps/ingest-env"),
    // /healthz never fails on NESO or database trouble, so an upstream outage can't restart-loop it.
    // /readyz (database) and /status are on the private network.
    deploy: deploy("pnpm --filter @mx/ingest-env start", "/healthz"),
    // One replica is enough for staging. Writes are safe with more: a per-dataset lock means a
    // change is appended once.
    replicas: { sfo: 1 },
    networking: { privateNetworkEndpoint: "ingest-env" },
    env: {
      NODE_ENV: "production",
      LOG_LEVEL: "info",
      DATABASE_URL: db.env.DATABASE_URL,
      // Railway health-checks the port in PORT; the service listens on ENV_HEALTH_PORT.
      PORT: INGEST_ENV_PORT,
      ENV_HEALTH_PORT: INGEST_ENV_PORT,
      NESO_BASE_URL: "https://api.neso.energy",
    },
  });

  return project("authentic-rebirth", {
    variables: { managed: true },
    resources: [db, facilitator, gateway, reconciler, ingestEnv],
  });
});
